#!/usr/bin/env python3
"""Generate app/src/main/res/values-tn/*.xml from tools/tn_draft.py, and docs/SETSWANA_REVIEW.md
from the English and Setswana resource files.

  python3 tools/gen_setswana.py          # write values-tn from the draft, then the review doc
  python3 tools/gen_setswana.py --doc    # only rebuild the review doc from the XML (after edits)

Confidence lives in a comment before each string in values-tn (<!-- confidence: high -->), so a
reviewer can edit the XML directly and change it to "reviewed".
"""
import re, sys, html, pathlib
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
FILES = ["strings.xml", "strings_academy.xml"]
CONF = {"H": "high", "M": "medium", "L": "low"}
PH = re.compile(r"%\d+\$[sd]")

def english():
    out = []  # (file, key, quantity|None, text)
    for f in FILES:
        for e in ET.parse(RES / "values" / f).getroot():
            if e.get("translatable") == "false":
                continue
            if e.tag == "string":
                out.append((f, e.get("name"), None, e.text or ""))
            elif e.tag == "plurals":
                for it in e:
                    out.append((f, e.get("name"), it.get("quantity"), it.text or ""))
    return out

def esc(t):
    # Values in the draft are already Android-escaped for quotes (\" and \'); escape XML and bare apostrophes.
    t = t.replace("&", "&amp;").replace("<", "&lt;")
    t = re.sub(r"(?<!\\)'", r"\\'", t)
    return t

def write_xml():
    sys.path.insert(0, str(ROOT / "tools"))
    from tn_draft import T
    en = english()
    missing = [k + (f"#{q}" if q else "") for _, k, q, _ in en if (k + (f"#{q}" if q else "")) not in T]
    if missing:
        sys.exit(f"draft is missing: {missing}")
    (RES / "values-tn").mkdir(exist_ok=True)
    for f in FILES:
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Setswana (tn) draft. Generated by tools/gen_setswana.py; edit freely, then rerun it with the doc option. -->",
                 "<resources>"]
        done_plurals = set()
        for ff, k, q, src in en:
            if ff != f:
                continue
            if q is None:
                text, c = T[k]
                if sorted(PH.findall(text)) != sorted(PH.findall(src)):
                    sys.exit(f"placeholder mismatch in {k}: {src!r} vs {text!r}")
                lines.append(f"    <!-- confidence: {CONF[c]} -->")
                lines.append(f'    <string name="{k}">{esc(text)}</string>')
            elif k not in done_plurals:
                done_plurals.add(k)
                items = [(qq, T[f"{k}#{qq}"]) for fff, kk, qq, _ in en if fff == f and kk == k]
                worst = min((CONF[c] for _, (_, c) in items), key=["low", "medium", "high"].index)
                lines.append(f"    <!-- confidence: {worst} -->")
                lines.append(f'    <plurals name="{k}">')
                for qq, (text, _) in items:
                    lines.append(f'        <item quantity="{qq}">{esc(text)}</item>')
                lines.append("    </plurals>")
        lines.append("</resources>")
        (RES / "values-tn" / f).write_text("\n".join(lines) + "\n", encoding="utf-8")

def read_tn():
    vals, conf = {}, {}
    for f in FILES:
        raw = (RES / "values-tn" / f).read_text(encoding="utf-8")
        for m in re.finditer(r"<!-- confidence: (\w+) -->\s*<(string|plurals) name=\"([^\"]+)\"", raw):
            conf[m.group(3)] = m.group(1)
        for e in ET.parse(RES / "values-tn" / f).getroot():
            if e.tag == "string":
                vals[(e.get("name"), None)] = e.text or ""
            elif e.tag == "plurals":
                for it in e:
                    vals[(e.get("name"), it.get("quantity"))] = it.text or ""
    return vals, conf

def write_doc():
    en = english()
    tn, conf = read_tn()
    cell = lambda s: s.replace("\\'", "'").replace('\\"', '"').replace("\\n", " ").replace("|", "\\|")
    rows, counts = [], {"high": 0, "medium": 0, "low": 0, "reviewed": 0}
    for f, k, q, src in en:
        key = k + (f" ({q})" if q else "")
        c = conf.get(k, "medium")
        counts[c] = counts.get(c, 0) + 1
        rows.append(f"| `{key}` | {cell(src)} | {cell(tn.get((k, q), '**MISSING**'))} | {c} |")
    total = len(rows)
    need = total - counts.get("reviewed", 0)
    doc = f"""# Setswana translation review

Mmele ships English (default) and a **draft** Setswana (`tn`) translation. Every Setswana string
below was drafted by the developer's assistant, not by a native speaker, so **all {need} of {total}
strings need review** before the Setswana UI is promoted (the high-confidence ones should be quick).

How to correct: edit `app/src/main/res/values-tn/strings.xml` or `strings_academy.xml` directly
(keep `%1$s` / `%1$d` placeholders, write an apostrophe as `\\'`), change the comment above the
string to `<!-- confidence: reviewed -->`, then run `python3 tools/gen_setswana.py --doc` to rebuild
this table. `LocalizationTest` checks that every key exists with the same placeholders.

Conventions in the draft (please confirm or replace):

- Game terms as you use them: **Go baya** (place), **Go sutisa** (move), **Go fofa** (fly),
  **go tswala** (locked in), **Mmele**, **Khutlotharo**, **kgomo / dikgomo** (cow / cows).
- *Mill* = **mola** (line); *shoot* = **thunya**; *opponent* = **mophenyisani**;
  *Dark / Light* sides = **Lefifi / Lesweu**; *Academy* = **Sekolo**; *Hint* = **Thuso**.
- Place names stay as Batswana write them (Okavango, Chobe, Makgadikgadi, Tsodilo, Kgalagadi).
- Bird names (lapwing, roller) are low confidence: please supply the names you know.

Counts: {counts['high']} high, {counts['medium']} medium, {counts['low']} low confidence, {counts.get('reviewed', 0)} reviewed.

| Key | English | Draft Setswana | Confidence |
|---|---|---|---|
""" + "\n".join(rows) + "\n"
    (ROOT / "docs/SETSWANA_REVIEW.md").write_text(doc, encoding="utf-8")
    print(f"{total} strings, {need} need review ({counts})")

if __name__ == "__main__":
    if "--doc" not in sys.argv:
        write_xml()
    write_doc()
